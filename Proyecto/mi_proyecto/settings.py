# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases
#
# El motor se define por variable de entorno DB_ENGINE:
#   - 'sqlite3' (por defecto): para desarrollo local, sin instalar nada más.
#   - 'mysql': para el despliegue en la instancia EC2 con phpMyAdmin.

DB_ENGINE = config('DB_ENGINE', default='sqlite3').lower()

if DB_ENGINE == 'mysql':
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': config('DB_NAME'),
            'USER': config('DB_USER'),
            'PASSWORD': config('DB_PASSWORD'),
            'HOST': config('DB_HOST', default='localhost'),
            'PORT': config('DB_PORT', default='3306'),
            'OPTIONS': {
                'charset': 'utf8mb4',
            },
        }
    }
elif DB_ENGINE == 'sqlite3':
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }
else:
    raise ValueError("DB_ENGINE debe ser 'sqlite3' o 'mysql'.")


